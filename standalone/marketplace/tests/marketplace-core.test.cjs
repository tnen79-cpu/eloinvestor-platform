const assert=require('node:assert/strict');
const M=require('../assets/js/marketplace-core.js');
assert.equal(M.roi({monthly_profit:500}),null,'profit alone is not a percentage');
assert.equal(M.roi({price:25000,monthly_profit:500}),24);
assert.equal(M.roi({price:25000,monthly_profit:0}),0);
assert.equal(M.roi({price:25000}),null);
assert.equal(M.roi({price:0,monthly_profit:500}),null);
assert.equal(M.roi({roi:0,price:25000,monthly_profit:500}),0);
assert.equal(M.roi({price:25000,monthly_profit:-500}),-24);
assert.equal(M.roi({price:'invalid',monthly_profit:500}),null);
assert(M.matches({category:'restaurants'},{category:'مطاعم'}));
assert(M.matches({category:'تقنية'},{category:'tech'}));
assert(!M.matches({category:'commerce'},{category:'restaurants'}));
assert(!M.verified({is_verified:true,verification_status:'pending'}));
assert(M.matches({price:100,verification_status:'verified'},{min:'100',max:'100',verified:'1'}));
assert(!M.matches({price:101},{max:'100'}));
assert(!M.matches({price:500},{roiMin:'1'}));
assert(M.matches({type:'مشروع للبيع',location:'مسقط - بوشر'},{type:'بيع',location:'مسقط'}));
const f=M.filters(new URLSearchParams('q=cafe&cat=restaurants&max=25000&verified=1'));
assert.equal(f.category,'restaurants');assert.equal(f.max,'25000');assert.equal(f.verified,'1');
assert.deepEqual(M.sort([{id:1,price:null},{id:2,price:100}], 'price_asc').map(p=>p.id),[2,1]);
assert.deepEqual(M.sort([{id:1,price:100},{id:2,price:100,monthly_profit:0}], 'roi_desc').map(p=>p.id),[2,1]);
console.log('Marketplace core regression tests passed.');
